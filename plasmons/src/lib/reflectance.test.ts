import { describe, expect, it } from "vitest";
import { defaultParams, wavelength } from "./constants";
import { buildLayers, type Layer } from "./layers";
import { reflectance } from "./reflectance";
import { steps } from "./plot";
import fixtures from "./fixtures/tmm.json";

describe("reflectance", () => {
  const angles = steps(40, 80, 0.5);

  it("returns one value in [0, 1] per angle", () => {
    const r = reflectance(buildLayers(defaultParams), wavelength, angles);
    expect(r).toHaveLength(angles.length);
    for (const v of r) {
      expect(v).toBeGreaterThanOrEqual(0);
      expect(v).toBeLessThanOrEqual(1);
    }
  });
});

// Reference curves from tmm, generated by `make fixtures`.
describe("reflectance matches tmm", () => {
  const tolerance = 1e-9;

  it.each(fixtures.cases.map((c) => [c.name, c] as const))("%s", (_, c) => {
    const layers: Layer[] = c.layers.map((l, i) => ({
      name: `layer ${i}`,
      index: { re: l.re, im: l.im },
      thickness: l.thickness ?? Infinity,
    }));

    const actual = reflectance(layers, c.wavelength, c.angles);
    expect(actual).toHaveLength(c.angles.length);

    // Report the worst angle rather than hundreds of individual failures.
    let worst = { angle: NaN, expected: NaN, actual: NaN, error: 0 };
    c.reflectance.forEach((expected, i) => {
      const error = Math.abs(actual[i] - expected);
      if (!(error <= worst.error)) {
        worst = { angle: c.angles[i], expected, actual: actual[i], error };
      }
    });
    expect(worst.error, `worst at ${worst.angle}°: expected ${worst.expected}, got ${worst.actual}`).toBeLessThan(tolerance);
  });
});
